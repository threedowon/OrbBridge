const assert = require('node:assert/strict');
const IssuePanel = require('../admin/hardware/issues.js');
const p = new IssuePanel(null);
for (let i=0;i<10;i++) p.condition('port', true, 'COM');
assert.equal(p.live.get('port').count,1);
p.condition('port',false);
assert.equal(p.live.get('port').active,false);
p.condition('port',true,'COM');
assert.equal(p.live.get('port').count,2);
p.condition('resolved',true,'Old');p.condition('resolved',false);
p.records=[{key:'crc',count:5}];p.clear();
assert.equal(p.live.size,1);
assert.equal(p.live.get('port').active,true);
assert.deepEqual(p.records,[]);
p.status({input_mode:'table',serial:{connected:false},hardware:{connections:[]},slaves:[]});
assert.equal(p.live.get('port').active,false);
p.status({input_mode:'serial',serial:{connected:true},hardware:{mode:'direct',connections:[]},slaves:[{slave:2,online:false,has_heartbeat:false}]});
assert.equal(p.live.has('slave:2'),false);
p.status({input_mode:'serial',serial:{connected:true},hardware:{mode:'master',connections:[{port:'COM19',health:'alive'}]},slaves:[{slave:2,online:false,has_heartbeat:false}],game:{cells:{'2:4':{orb_id:'__recovered__:2:4'}}}});
assert.equal(p.live.get('slave:2').active,true);
assert.equal(p.pendingSlots.has('2:4'),true);
console.log('Important issue state tests passed');
